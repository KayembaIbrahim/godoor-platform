/**
 * Pre-paint theme resolution.
 *
 * `useThemeEffect` can only run after hydration, so without this the server
 * markup (`class="light"`) would paint first and dark-mode users would get a
 * white flash on every page load. This reads the same persisted key zustand
 * uses and applies the class before the browser paints any body content.
 *
 * Kept in sync with `src/lib/theme-store.ts` (storage key + light/dark tokens).
 */
const themePreloadScript = `
(function () {
  try {
    var raw = localStorage.getItem("godoor-theme-v5-white");
    var stored = raw ? JSON.parse(raw) : null;
    var theme = (stored && stored.state && stored.state.theme) || "light";
    var resolved = theme === "system"
      ? (window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light")
      : theme;
    var root = document.documentElement;
    root.classList.remove("light", "dark");
    root.classList.add(resolved);
    var meta = document.querySelector('meta[name="theme-color"]');
    if (meta) meta.setAttribute("content", resolved === "dark" ? "#0A0A0B" : "#FFFFFF");
  } catch (e) {}
})();
`.trim();

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  maximumScale: 1,
  themeColor: "#FFFFFF",
  // REQUIRED for the safe-area insets to report anything. Without
  // `viewport-fit=cover`, `env(safe-area-inset-*)` resolves to 0 on every
  // device, so a `sticky top-0` header is drawn underneath the status bar
  // and the dynamic island when the app runs fullscreen/standalone — the
  // header row (logo, location, search) disappears behind the notch.
  // The padding side of the fix lives in `.safe-area-top` / `.safe-area-bottom`.
  viewportFit: "cover",
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    // The script rewrites the class on <html>, so React must accept the DOM as-is.
    <html
      lang="en"
      className={`light ${poppins.variable} ${inter.variable}`}
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: themePreloadScript }} />
      </head>
      <body className="font-sans antialiased">
        <ThemeEffect />
        <HeaderClient />
        <ClientProviders>
          <main className="min-h-0">{children}</main>
        </ClientProviders>
      </body>
    </html>
  );
}
